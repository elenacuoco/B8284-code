"""
EXAMPLE 4: Arithmetic Operators
All Python mathematical operators
"""

# Define two numbers
a = 10
b = 3

print("a =", a)
print("b =", b)
print()

# Basic operations
print("Addition:           a + b =", a + b)
print("Subtraction:        a - b =", a - b)
print("Multiplication:     a * b =", a * b)
print("Division:           a / b =", a / b)
print("Floor division:     a // b =", a // b)
print("Remainder (modulo): a % b =", a % b)
print("Power:              a ** b =", a ** b)

print("\n--- String operations ---")
first_name = "Python"
last_name = "Programming"
full = first_name + " " + last_name
print("Concatenation:", full)

# String repetition
print("Repetition:", "Python! " * 3)
